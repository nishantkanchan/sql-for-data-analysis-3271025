#!/usr/bin/env python3
"""Write docs/CONTENT_STATUS.md: what content exists, coverage, and quality signals.

Usage: python3 content/scripts/content_report.py
"""
from __future__ import annotations

import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "content" / "data"
OUT = ROOT / "docs" / "CONTENT_STATUS.md"
DEV = re.compile(r"[ऀ-ॿ]")


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def main() -> None:
    lines = ["# Content status", "", "_Generated by `content/scripts/content_report.py`._", ""]

    # Corpus
    lines += ["## Sanskrit corpus", "", "| File | Text | Verses | Chapters |", "|---|---|---:|---:|"]
    corpus_index: dict[str, dict] = {}
    for p in sorted((DATA / "corpus").glob("*.json")):
        d = load(p)
        vs = d.get("verses", [])
        chapters = {(v["sthana"], v["chapter"]) for v in vs}
        lines.append(f"| `{p.name}` | {d.get('meta', {}).get('title', '')} | {len(vs):,} | {len(chapters)} |")
        for v in vs:
            corpus_index.setdefault(v["id"], v)
    lines.append("")

    # Translations
    tdir = DATA / "translations"
    lines += ["## Translations (English + Hindi + word meanings)", ""]
    total = 0
    with_modern = 0
    importance = Counter()
    rows = []
    for p in sorted(tdir.rglob("*.json"), key=lambda x: (x.parts[-3], x.parts[-2], int(x.stem) if x.stem.isdigit() else 0)):
        try:
            d = load(p)
        except Exception as e:  # noqa: BLE001
            rows.append(f"| {p.relative_to(tdir)} | invalid JSON: {e} | | | |")
            continue
        vs = d.get("verses", [])
        total += len(vs)
        m = sum(1 for v in vs if v.get("modern_correlation"))
        with_modern += m
        importance.update(v.get("importance") for v in vs)
        ch = d.get("chapter", {})
        rows.append(f"| {ch.get('id', p.stem)} | {ch.get('title_iast', '')} | {len(vs)} | {m} | {sum(1 for v in vs if v.get('importance') == 'high')} |")
    lines += [f"**{total:,} verses translated**, {with_modern:,} with a modern-science correlation. "
              f"Importance: {dict(importance)}.", "",
              "| Chapter | Title | Verses | Modern corr. | High-yield |", "|---|---|---:|---:|---:|"] + rows + [""]

    # Quiz
    qdir = DATA / "quiz"
    lines += ["## Quiz bank", "", "| Subject | Questions | Topics | Types | Difficulty |", "|---|---:|---:|---|---|"]
    qtotal = 0
    for p in sorted(qdir.glob("*.json")):
        try:
            qs = load(p).get("questions", [])
        except Exception as e:  # noqa: BLE001
            lines.append(f"| {p.stem} | invalid: {e} | | | |")
            continue
        qtotal += len(qs)
        topics = {q.get("topic_id") for q in qs}
        lines.append(f"| {p.stem} | {len(qs)} | {len(topics)} | {dict(Counter(q.get('type') for q in qs))} | {dict(Counter(q.get('difficulty') for q in qs))} |")
    lines += ["", f"**{qtotal:,} questions total.**", ""]

    # Glossary
    gp = DATA / "glossary.json"
    if gp.exists():
        terms = load(gp).get("terms", [])
        cats = Counter(t.get("category") for t in terms)
        lines += ["## Glossary", "", f"**{len(terms):,} terms.**", "", "| Category | Terms |", "|---|---:|"]
        lines += [f"| {c} | {n} |" for c, n in cats.most_common()] + [""]

    # Syllabus
    sp = DATA / "syllabus.json"
    if sp.exists():
        s = load(sp)
        lines += ["## Syllabus", ""]
        for prof in s.get("professionals", []):
            subs = prof.get("subjects", [])
            ntopics = sum(len(pp.get("topics", [])) for sub in subs for pp in sub.get("papers", []))
            lines.append(f"- **{prof.get('name_en')}**: {len(subs)} subjects, {ntopics} topics: " + ", ".join(sub.get("name_en", "") for sub in subs))
        lines.append("")

    lines += ["## Review status", "", "All generated content is `ai_draft` until a subject expert reviews it. "
              "Run `python3 content/scripts/validate_content.py` for schema checks.", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
